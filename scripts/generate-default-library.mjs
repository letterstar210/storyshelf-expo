import fs from 'node:fs/promises';
import path from 'node:path';
import JSZip from 'jszip';
import XLSX from 'xlsx';

const HEADER_ALIASES = {
  'ชื่อเรื่อง': 'title',
  title: 'title',
  name: 'title',
  'รูปปก': 'coverImage',
  cover: 'coverImage',
  coverimage: 'coverImage',
  image: 'coverImage',
  'ตอนที่': 'episode',
  episode: 'episode',
  chapter: 'episode',
  'ลิงค์ตอนล่าสุด': 'link',
  'ลิงก์ตอนล่าสุด': 'link',
  link: 'link',
  url: 'link',
};

const OUTPUT_PATH = path.resolve(
  'src/constants/defaultEntries.generated.ts'
);

const normalizeHeader = (value) =>
  String(value ?? '')
    .trim()
    .toLowerCase()
    .replace(/\s+/g, '');

const toText = (value) => {
  if (value === undefined || value === null) {
    return '';
  }

  return String(value).trim();
};

const isRemoteImage = (value) => /^https?:\/\//i.test(value.trim());

const readWorkbookBase64FromInput = async (inputPath) => {
  const extension = path.extname(inputPath).toLowerCase();

  if (extension === '.zip') {
    const archiveBuffer = await fs.readFile(inputPath);
    const archive = await JSZip.loadAsync(archiveBuffer);
    const workbookFile = Object.values(archive.files).find(
      (file) => !file.dir && /\.(xlsx|xls)$/i.test(file.name)
    );

    if (!workbookFile) {
      throw new Error('No Excel workbook found inside the ZIP file.');
    }

    return {
      sourceLabel: `${path.basename(inputPath)} -> ${path.basename(workbookFile.name)}`,
      base64: await workbookFile.async('base64'),
    };
  }

  if (extension === '.xlsx' || extension === '.xls') {
    const workbookBuffer = await fs.readFile(inputPath);
    return {
      sourceLabel: path.basename(inputPath),
      base64: workbookBuffer.toString('base64'),
    };
  }

  throw new Error('Please provide a .zip, .xlsx, or .xls file.');
};

const parseEntries = (base64) => {
  const workbook = XLSX.read(base64, { type: 'base64' });
  const entries = [];

  for (const sheetName of workbook.SheetNames) {
    const sheet = workbook.Sheets[sheetName];
    if (!sheet) {
      continue;
    }

    const rows = XLSX.utils.sheet_to_json(sheet, {
      header: 1,
      defval: '',
      raw: false,
    });

    if (!rows.length) {
      continue;
    }

    const headerRow = (rows[0] ?? []).map((cell) => normalizeHeader(cell));
    const headerMap = headerRow.map((header) => HEADER_ALIASES[header] ?? null);
    const hasKnownHeaders = headerMap.some(Boolean);

    for (let rowIndex = 1; rowIndex < rows.length; rowIndex += 1) {
      const row = rows[rowIndex] ?? [];
      const draft = {
        title: '',
        episode: '',
        link: '',
        coverImage: '',
      };

      if (hasKnownHeaders) {
        for (let columnIndex = 0; columnIndex < row.length; columnIndex += 1) {
          const mappedField = headerMap[columnIndex];
          if (!mappedField) {
            continue;
          }

          const textValue = toText(row[columnIndex]);
          if (!textValue) {
            continue;
          }

          if (mappedField === 'coverImage') {
            draft.coverImage = isRemoteImage(textValue) ? textValue : '';
            continue;
          }

          draft[mappedField] = textValue;
        }
      } else {
        draft.title = toText(row[0]);
        draft.coverImage = isRemoteImage(toText(row[1])) ? toText(row[1]) : '';
        draft.episode = toText(row[2]);
        draft.link = toText(row[3]);
      }

      if (!draft.title) {
        continue;
      }

      entries.push(draft);
    }
  }

  return entries;
};

const toTypeScriptModule = (entries, sourceLabel) => {
  const timestamp = new Date().toISOString();
  const normalizedEntries = entries.map((entry, index) => ({
    id: `default-${index + 1}`,
    title: entry.title,
    episode: entry.episode,
    link: entry.link,
    coverImage: entry.coverImage,
    createdAt: timestamp,
    updatedAt: timestamp,
  }));

  return `import { Entry } from '../types/entry';

// Generated by scripts/generate-default-library.mjs
// Source: ${sourceLabel}
export const DEFAULT_ENTRIES: Entry[] = ${JSON.stringify(
    normalizedEntries,
    null,
    2
  )};
`;
};

const inputPath = process.argv[2];

if (!inputPath) {
  console.error(
    'Usage: node scripts/generate-default-library.mjs "<path-to-zip-or-workbook>"'
  );
  process.exit(1);
}

const absoluteInputPath = path.resolve(inputPath);

try {
  const { base64, sourceLabel } = await readWorkbookBase64FromInput(
    absoluteInputPath
  );
  const entries = parseEntries(base64);

  if (entries.length === 0) {
    throw new Error('No importable rows were found in the provided file.');
  }

  const moduleContents = toTypeScriptModule(entries, sourceLabel);
  await fs.writeFile(OUTPUT_PATH, moduleContents, 'utf8');

  console.log(`Generated ${entries.length} default entries.`);
  console.log(`Saved to ${OUTPUT_PATH}`);
} catch (error) {
  console.error(
    error instanceof Error ? error.message : 'Failed to generate default library.'
  );
  process.exit(1);
}
